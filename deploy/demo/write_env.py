#!/usr/bin/env python3
"""Create or check the demo environment file. Never prints a value, only key names.

    python3 write_env.py create --path /etc/visioncast/visioncast.env --host 64-225-16-137.sslip.io
    python3 write_env.py check  --path /etc/visioncast/visioncast.env --host 64-225-16-137.sslip.io

``create`` refuses to overwrite an existing file; it writes fresh random secrets with
mode 0600 (owner root). ``check`` verifies ownership, mode, that every required key is
present and non-empty, and that the fixed (non-secret) values still match this
deployment; it reports mismatching key names only.

Every value is restricted to characters that systemd ``EnvironmentFile=`` and a POSIX
shell ``.`` parse identically (no quotes, spaces, ``$`` or backslashes).
Standard library only; run with the system python3 as root.
"""
import argparse
import base64
import os
import re
import secrets
import sys

SITE_ORIGIN = "https://visioncast-ten.vercel.app"
SITE_HOST = "visioncast-ten.vercel.app"
OWNER_ORIGIN = "http://localhost:8081"  # nginx owner-only listener, reached through an SSH tunnel
STATIC_ROOT = "/srv/visioncast/static"
DB_NAME = "visioncast"
DB_USER = "visioncast"  # equals the service user: local socket, peer authentication

SECRET_KEYS = ("DJANGO_SECRET_KEY", "POSTGRES_PASSWORD", "INTEGRATION_MASTER_KEY")
HOST_RE = re.compile(r"^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$")
SAFE_VALUE_RE = re.compile(r"^[A-Za-z0-9_./:,{}=@-]*$")


def fixed_values(host):
    return {
        "DJANGO_DEBUG": "0",
        "DJANGO_ALLOWED_HOSTS": f"{host},localhost",
        "DJANGO_CSRF_TRUSTED_ORIGINS": f"https://{host},{OWNER_ORIGIN}",
        # Safe only because every nginx server block overwrites X-Forwarded-Proto.
        "DJANGO_TRUST_X_FORWARDED_PROTO": "1",
        # Short HSTS: the sslip.io name is tied to a demo IP that may be released later.
        "DJANGO_HSTS_SECONDS": "86400",
        "DJANGO_STATIC_ROOT": STATIC_ROOT,
        "DJANGO_LOG_LEVEL": "INFO",
        "PUBLIC_BASE_URL": f"https://{host}",
        "PUBLIC_EVENT_URL_TEMPLATE": f"{SITE_ORIGIN}/events/{{slug}}",
        "WEBINAR_ALLOWED_ORIGINS": SITE_ORIGIN,
        "THANK_YOU_REDIRECT_HOSTS": SITE_HOST,
        # Empty: no webhook destination can be configured.
        "WEBHOOK_HOST_ALLOWLIST": "",
        "POSTGRES_HOST": "/var/run/postgresql",
        "POSTGRES_PORT": "5432",
        "POSTGRES_DB": DB_NAME,
        "POSTGRES_USER": DB_USER,
        "POSTGRES_SSLMODE": "disable",
        "EMAIL_DELIVERY": "disabled",
        "DEFAULT_FROM_EMAIL": "noreply@visioncast-demo.invalid",
        "RATE_LIMIT_ENABLED": "1",
        # nginx overwrites X-Forwarded-For with $remote_addr (one trusted hop).
        "RATE_LIMIT_TRUST_X_FORWARDED_FOR": "1",
        "RATE_LIMIT_TRUSTED_PROXY_COUNT": "1",
        "CAPABILITY_COOKIE_NAME": "webinar_session",
    }


def secret_values():
    return {
        "DJANGO_SECRET_KEY": secrets.token_urlsafe(50),
        # Settings require a value; peer authentication over the socket does not use it.
        "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
        "INTEGRATION_MASTER_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
    }


def parse(path):
    values = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, sep, value = line.partition("=")
            if sep:
                values[key.strip()] = value.strip()
    return values


def create(path, host):
    if os.path.lexists(path):
        sys.exit(f"{path} already exists; refusing to overwrite it.")
    parent = os.path.dirname(path)
    st = os.stat(parent)
    if st.st_uid != 0 or st.st_mode & 0o077:
        sys.exit(f"{parent} must be owned by root with mode 0700.")
    values = {**fixed_values(host), **secret_values()}
    for key, value in values.items():
        if not SAFE_VALUE_RE.match(value):
            sys.exit(f"Refusing to write {key}: unexpected characters.")
    lines = ["# VisionCast demo environment. Generated by deploy/demo/write_env.py. Root only; never print."]
    lines += [f"{key}={value}" for key, value in values.items()]
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        os.write(fd, ("\n".join(lines) + "\n").encode("utf-8"))
        os.fsync(fd)
    finally:
        os.close(fd)
    print(f"Created {path} (mode 0600) with keys: " + ", ".join(values))


def check(path, host):
    st = os.stat(path)
    problems = []
    if st.st_uid != 0 or st.st_mode & 0o077:
        problems.append("file must be owned by root with mode 0600")
    values = parse(path)
    for key in SECRET_KEYS:
        if not values.get(key):
            problems.append(f"{key} missing or empty")
    for key, expected in fixed_values(host).items():
        if values.get(key, None if expected else "") != expected:
            problems.append(f"{key} differs from this deployment's value")
    for key in ("BOOTSTRAP_ADMIN_PASSWORD", "SMTP_PASSWORD", "SMTP_HOST", "DJANGO_TEST_SQLITE"):
        if values.get(key):
            problems.append(f"{key} must not be set")
    if problems:
        sys.exit(f"{path}: " + "; ".join(problems))
    print(f"{path}: ok ({len(values)} keys; values not shown)")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=["create", "check"])
    parser.add_argument("--path", required=True)
    parser.add_argument("--host", required=True)
    args = parser.parse_args()
    if os.geteuid() != 0:
        sys.exit("Run as root.")
    if not HOST_RE.match(args.host):
        sys.exit("--host must be a lowercase DNS name.")
    (create if args.action == "create" else check)(args.path, args.host)


if __name__ == "__main__":
    main()
