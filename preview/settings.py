# ---------------------------------------------------------------------------
# Outbound network refusal (defence in depth; the worker is never started).
# Applies to Python code in every process that loads these settings. It is not
# an OS firewall: pip runs before Django and needs PyPI.
# ---------------------------------------------------------------------------

_LOCAL_NAMES = {"localhost", "", "0.0.0.0", "::"}


def _is_local(host):
    if host is None:
        return True
    if isinstance(host, bytes):
        host = host.decode("ascii", "replace")
    host = str(host).strip("[]").split("%", 1)[0].lower()
    if host in _LOCAL_NAMES:
        return True
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


def _refuse_outbound(event, args):
    if event in ("socket.getaddrinfo", "socket.gethostbyname", "socket.gethostbyname_ex", "socket.gethostbyaddr"):
        host = args[0] if args else None
    elif event in ("socket.connect", "socket.sendto", "socket.sendmsg"):
        address = args[1] if len(args) > 1 else None
        if not isinstance(address, tuple):
            return  # AF_UNIX path or unsupported family details
        host = address[0]
    else:
        return
    if not _is_local(host):
        raise PermissionError("Outbound network access is disabled in the webinar preview.")


sys.addaudithook(_refuse_outbound)
