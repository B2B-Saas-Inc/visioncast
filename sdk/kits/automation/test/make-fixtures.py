#!/usr/bin/env python3
"""Regenerate sdk/kits/automation/test/fixtures/deliveries.json.

The fixture is signed with ``examples/verify_webhook.py``'s ``compute_signature``, which is
the receiver-side twin of ``webinars.crypto.sign_webhook`` (``tests/test_verify_webhook_example.py``
proves they agree). The Node tests then verify the same bytes with the Zapier code step and
the Make / n8n simulations, so every recipe is checked against the backend's algorithm, not
a re-implementation of it. Deterministic: fixed timestamp, ids and secret (not real).

    python3 sdk/kits/automation/test/make-fixtures.py
"""
import importlib.util
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[4]
spec = importlib.util.spec_from_file_location("verify_webhook", ROOT / "examples" / "verify_webhook.py")
verify_webhook = importlib.util.module_from_spec(spec)
spec.loader.exec_module(verify_webhook)

SECRET = "test-secret-not-real-0123456789"
PREVIOUS_SECRET = "previous-secret-not-real-9876543210"
NOW = 1_700_000_000
DELIVERY_ID = "8d3f1c3e-0000-4000-8000-000000000001"

# A trimmed registration.created payload with the same shape as docs/webhooks.md (fake data).
PAYLOAD = {
    "schemaVersion": "1",
    "eventType": "registration.created",
    "occurredAt": "2026-03-02T10:15:00Z",
    "identity": {"personId": "6f1c2a8e-1111-4c1d-9a7e-000000000001", "email": "ada@example.com", "verified": True},
    "profile": {"email": "ada@example.com", "firstName": "Ada", "lastName": "Example", "company": "Example Ltd",
                "jobTitle": "Engineer", "name": None, "phone": None, "companySize": None, "customFields": {}},
    "registration": {"id": "0b7e9d4c-2222-4b8f-8c3a-000000000002", "status": "registered", "attendance": "unknown",
                     "formVersion": "default-v1", "identityVerified": True,
                     "createdAt": "2026-03-02T10:15:00Z", "updatedAt": "2026-03-02T10:15:00Z"},
    "event": {"id": "3c9d6b1a-3333-4e2f-a1b2-000000000003", "slug": "intro-to-widgets", "title": "Intro to Widgets",
              "occurrence": {"id": "9a8b7c6d-4444-4d3c-b2a1-000000000004", "startsAt": "2026-03-10T15:00:00Z",
                             "endsAt": "2026-03-10T15:45:00Z", "timezone": "Europe/London", "status": "scheduled"}},
    "delivery_metadata": {"deliveryId": DELIVERY_ID, "destinationId": "7d6c5b4a-6666-4f5e-8d7c-000000000006",
                          "destinationKind": "generic", "eventType": "registration.created",
                          "createdAt": "2026-03-02T10:15:00Z", "attempt": 1},
}


def main():
    # Compact JSON with sorted keys and non-ASCII escaped: the bytes ``webinars.delivery`` sends.
    body = json.dumps(PAYLOAD, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    raw = body.encode("utf-8")
    fixture = {
        "note": "Generated by make-fixtures.py with examples/verify_webhook.py compute_signature. Fake data; the secret is not real.",
        "secret": SECRET,
        "previousSecret": PREVIOUS_SECRET,
        "toleranceSeconds": verify_webhook.TOLERANCE_SECONDS,
        "now": NOW,
        "deliveryId": DELIVERY_ID,
        "timestamp": str(NOW),
        "eventType": PAYLOAD["eventType"],
        "body": body,
        "signature": verify_webhook.compute_signature(SECRET, DELIVERY_ID, NOW, raw),
        # Header value during secret rotation: old then new, comma separated (docs/webhooks.md).
        "rotationSignature": verify_webhook.compute_signature(PREVIOUS_SECRET, DELIVERY_ID, NOW, raw)
        + ", "
        + verify_webhook.compute_signature(SECRET, DELIVERY_ID, NOW, raw),
        "wrongSecretSignature": verify_webhook.compute_signature("wrong-secret", DELIVERY_ID, NOW, raw),
    }
    assert verify_webhook.verify_signature(SECRET, DELIVERY_ID, NOW, raw, fixture["signature"], now=NOW)
    out = pathlib.Path(__file__).resolve().parent / "fixtures" / "deliveries.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(fixture, indent=2) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
